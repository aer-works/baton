namespace Baton.Tests.Mutation;

/// <summary>
/// #1691: replays four REAL rooms' billed usage streams through the REAL
/// <see cref="TokenBudgetMonitor"/> and the REAL per-vendor <see cref="IWorkerUsageParser"/>, against
/// the sliding billed-rate trigger this issue added.
///
/// <para>
/// The issue's premise — stated in full in spec/baton.md §3 — was that room
/// <c>dispatch-implement-38c24d11</c> separates from normal traffic on billed RATE, and that a windowed
/// limit could therefore ship as a role default. These tests are the measurement
/// of that premise, and they REFUTE it: the mechanism does exactly what it was designed to, and the
/// proposed limit catches the runaway and a lane that produced its work alike. spec/baton.md §3 states
/// the finding and what follows from it; this file is what keeps §3 from becoming prose that drifts.
/// </para>
///
/// <para>
/// The fixture is <c>Fixtures/billed-rate-rooms.json</c>, generated by
/// <c>tools/room-rate-sweep/sweep.py --emit-fixture</c> from the rooms' own <c>.stdout.log</c> and
/// <c>flow.jsonl</c>. **Read that script's docstring before trusting any offset here** — it is where
/// the measured-vs-reconstructed distinction and the direction of the reconstruction's error are
/// stated, and neither is restated in this file. In one clause: claude offsets are measured, agy
/// offsets are not. What does NOT depend on any of it is the separation argument in
/// <see cref="CALIBRATION_no_rate_limit_separates_the_runaway_from_lanes_that_delivered"/> —
/// spec/baton.md §3 says why that one is assumption-free.
/// </para>
/// </summary>
public sealed class BilledRateReplayTests
{
    /// <summary>The limit #1691's own proposal named (W=5 min, R=250k). Operator-supplied here — NO role ships it.</summary>
    private const long ProposedRateLimit = 250_000;

    private const string RunawayRoom = "dispatch-implement-38c24d11";
    private const string NormalClaudeRoomA = "dispatch-implement-3dc5e21a";
    private const string NormalClaudeRoomB = "dispatch-implement-5d9686dd";

    /// <summary>
    /// A normal agy <c>implement</c> lane: exited <c>Natural</c>, never cancelled, and its 1,198,800
    /// billed total sits UNDER the shipped 1,200,000 token budget, so nothing else would have stopped
    /// it either. It is in this fixture because it is the cheapest possible refutation of #1691's
    /// premise — same vendor as the runaway, same role, faster burn, and it produced its work.
    /// </summary>
    private const string NormalAgyRoom = "dispatch-implement-6142bd07";

    private sealed record RoomFixture(
        string Vendor,
        bool OffsetsAreMeasured,
        double DurationSeconds,
        string ExitReason,
        bool Cancelled,
        bool ProducedWork,
        long TotalBilled,
        long PeakBilledIn5MinWindow,
        IReadOnlyList<(double OffsetSeconds, long In, long Out, long CacheCreation)> Samples);

    private static IReadOnlyDictionary<string, RoomFixture> LoadFixture()
    {
        var path = Path.Combine(AppContext.BaseDirectory, "Fixtures", "billed-rate-rooms.json");
        using var document = JsonDocument.Parse(File.ReadAllText(path));
        var rooms = new Dictionary<string, RoomFixture>(StringComparer.Ordinal);
        foreach (var room in document.RootElement.GetProperty("rooms").EnumerateObject())
        {
            var value = room.Value;
            var samples = new List<(double, long, long, long)>();
            foreach (var sample in value.GetProperty("samples").EnumerateArray())
            {
                samples.Add((
                    sample[0].GetDouble(),
                    sample[1].GetInt64(),
                    sample[2].GetInt64(),
                    sample[3].GetInt64()));
            }

            rooms[room.Name] = new RoomFixture(
                value.GetProperty("vendor").GetString()!,
                value.GetProperty("offsetsAreMeasured").GetBoolean(),
                value.GetProperty("durationSeconds").GetDouble(),
                value.GetProperty("exitReason").GetString()!,
                value.GetProperty("cancelled").GetBoolean(),
                value.GetProperty("producedWork").GetBoolean(),
                value.GetProperty("totalBilled").GetInt64(),
                value.GetProperty("peakBilledIn5MinWindow").GetInt64(),
                samples);
        }

        return rooms;
    }

    /// <param name="RoomsSwept">Every room the sweep read, both vendors, all exit reasons.</param>
    /// <param name="RoomsThatDelivered">The subset with at least one <c>executionSucceeded</c> and no <c>executionFailed</c>.</param>
    /// <param name="FasterAndDelivered">Of those, the ones that also out-burned the reference room.</param>
    private sealed record Separation(
        string ReferenceRoom,
        double ReferenceTokensPerMinute,
        int RoomsSwept,
        int RoomsThatDelivered,
        IReadOnlyList<(string Room, double TokensPerMinute)> FasterAndDelivered);

    private static Separation LoadSeparation()
    {
        var path = Path.Combine(AppContext.BaseDirectory, "Fixtures", "billed-rate-rooms.json");
        using var document = JsonDocument.Parse(File.ReadAllText(path));
        var value = document.RootElement.GetProperty("separation");
        var faster = new List<(string, double)>();
        foreach (var row in value.GetProperty("fasterAndDelivered").EnumerateArray())
        {
            faster.Add((row.GetProperty("room").GetString()!, row.GetProperty("tokensPerMinute").GetDouble()));
        }

        return new Separation(
            value.GetProperty("referenceRoom").GetString()!,
            value.GetProperty("referenceTokensPerMinute").GetDouble(),
            value.GetProperty("roomsSwept").GetInt32(),
            value.GetProperty("roomsThatDelivered").GetInt32(),
            faster);
    }

    private static IWorkerUsageParser ParserFor(string vendor) => vendor switch
    {
        "agy" => new AgyUsageParser(),
        "claude" => new ClaudeUsageParser(),
        _ => throw new ArgumentOutOfRangeException(nameof(vendor), vendor, "Unknown fixture vendor."),
    };

    private static string LineFor(string vendor, int index, long tokensIn, long tokensOut, long cacheCreation) => vendor switch
    {
        // The two shapes each vendor's real capture carries -- the SAME gates
        // StandardWorkerUsageParsers requires (#1686 review F4: agy's step_type must be
        // agent_response, claude's line must be type:assistant with a message.usage object).
        "agy" => "{\"event\":\"step_update\",\"step_update\":{\"state\":\"DONE\",\"step_type\":\"agent_response\",\"usage\":{"
            + "\"input_tokens\":" + tokensIn + ",\"output_tokens\":" + tokensOut
            + ",\"cache_creation_input_tokens\":" + cacheCreation + "}}}",
        // A distinct message.id per sample: the fixture already collapsed claude's repeated ids to
        // their first sighting at capture time, using the monitor's own rule. The dedupe itself is
        // #1686's and is pinned by TokenBudgetMonitorTests, not re-proven here.
        "claude" => "{\"type\":\"assistant\",\"message\":{\"id\":\"msg_" + index + "\",\"usage\":{"
            + "\"input_tokens\":" + tokensIn + ",\"output_tokens\":" + tokensOut
            + ",\"cache_creation_input_tokens\":" + cacheCreation + "}}}",
        _ => throw new ArgumentOutOfRangeException(nameof(vendor), vendor, "Unknown fixture vendor."),
    };

    /// <summary>
    /// Feeds one room's whole captured stream through a real monitor on a fake clock advanced to each
    /// sample's own offset.
    /// </summary>
    /// <param name="ArrestedAtSample">0-based index of the sample the monitor first arrested on, or -1 if it never did.</param>
    /// <param name="BilledAtArrest">
    /// The running billed Σ at that instant — what the room would ACTUALLY have spent, since a real
    /// arrest cancels the process. Null when there was no arrest. The replay deliberately keeps feeding
    /// the whole captured stream past an arrest (the monitor documents that as safe, and a real one
    /// does see a line or two during teardown), so the monitor's final snapshot is the room's full
    /// total and is not the figure to read for savings.
    /// </param>
    private sealed record ReplayResult(int ArrestedAtSample, long? BilledAtArrest, TokenBudgetMonitor Monitor);

    private static ReplayResult Replay(RoomFixture room, long? billedRateLimit)
    {
        var clock = new FakeTimeProvider(DateTimeOffset.UnixEpoch);
        var monitor = new TokenBudgetMonitor(
            budget: null, maxToolSteps: null, billedRateLimit: billedRateLimit,
            ParserFor(room.Vendor), clock);

        var arrestedAt = -1;
        long? billedAtArrest = null;
        var elapsed = 0.0;
        for (var i = 0; i < room.Samples.Count; i++)
        {
            var (offset, tokensIn, tokensOut, cacheCreation) = room.Samples[i];
            clock.Advance(TimeSpan.FromSeconds(Math.Max(0, offset - elapsed)));
            elapsed = Math.Max(elapsed, offset);
            monitor.OnStdoutLine(LineFor(room.Vendor, i, tokensIn, tokensOut, cacheCreation));
            if (monitor.Arrested && arrestedAt == -1)
            {
                arrestedAt = i;
                billedAtArrest = monitor.SnapshotUsage().BilledTokens;
            }
        }

        return new ReplayResult(arrestedAt, billedAtArrest, monitor);
    }

    [Fact]
    public void MECHANISM_the_runaway_room_arrests_at_usage_line_27_of_70_under_an_operator_supplied_250k_limit()
    {
        // The acceptance shape #1691 asked for: the real 38c24d11 stream through the real monitor
        // arrests at line N <= 30 of 70. It does -- N = 27 (0-indexed 26), at a cumulative billed of
        // 278,565 of the room's eventual 794,940, so 516,375 tokens (65%) are saved. What this does NOT
        // show, and what the issue assumed, is that 250,000 can therefore be a role DEFAULT: see the
        // false-positive test below, which is why no role ships one.
        var room = LoadFixture()[RunawayRoom];
        Assert.Equal("agy", room.Vendor);
        Assert.False(room.OffsetsAreMeasured); // reconstructed -- see this class's own remarks.

        var result = Replay(room, ProposedRateLimit);

        Assert.True(result.Monitor.Arrested);
        Assert.Equal(ArrestReason.BilledRate, result.Monitor.ArrestReasonValue);
        Assert.Equal(26, result.ArrestedAtSample);
        Assert.True(result.ArrestedAtSample < 30,
            $"arrest at 0-indexed {result.ArrestedAtSample} is not within the first 30 of {room.Samples.Count} usage lines.");
        Assert.Equal(278_565, result.BilledAtArrest);
        Assert.Equal(794_940, room.TotalBilled);
        // 516,375 of 794,940 never spent -- 64.96%, comfortably over the issue's ">=50% of the burn saved".
        Assert.True(room.TotalBilled - result.BilledAtArrest!.Value >= room.TotalBilled / 2);
    }

    [Fact]
    public void CONTROL_with_the_rate_trigger_disabled_the_same_runaway_replay_is_NOT_arrested()
    {
        // The discriminating half of the test above: identical fixture, identical monitor, identical
        // clock, ONLY billedRateLimit removed. Without this, an arrest above could be any trigger (or a
        // fixture artefact) rather than the one this issue added. Both budget and cap are already null
        // in Replay, so this isolates the new trigger completely: no arrest at all, and the full
        // 794,940 accumulates.
        var room = LoadFixture()[RunawayRoom];

        var result = Replay(room, billedRateLimit: null);

        Assert.False(result.Monitor.Arrested);
        Assert.Equal(-1, result.ArrestedAtSample);
        Assert.Null(result.Monitor.ArrestReasonValue);
        Assert.Equal(794_940, result.Monitor.SnapshotUsage().BilledTokens);
        // The peak is still MEASURED with no limit armed -- that is the half of the calibration a
        // monitor can supply going forward (spec/baton.md §3's phase 1).
        Assert.Equal(464_238, result.Monitor.SnapshotPeakBilledInWindow());
    }

    [Theory]
    [InlineData(NormalClaudeRoomA, 129_143)]
    [InlineData(NormalClaudeRoomB, 111_244)]
    public void The_two_normal_claude_rooms_full_streams_do_NOT_arrest_at_the_proposed_limit(string roomName, long expectedPeak)
    {
        // #1691's own acceptance bullet. These are the two rooms #1686 measured, replayed here through
        // the real ClaudeUsageParser with their lines' OWN timestamps -- the only rooms in the corpus
        // where the windowed rate is measured rather than reconstructed.
        //
        // Read the peaks with the caveat stated. **Corrected 2026-09-02 (#1707 review F8/L2): claude's
        // mid-stream `assistant` usage carries a message_start PLACEHOLDER on BOTH the input and output
        // side, not "output tokens" alone -- the missing input side is 3.7x the missing output side
        // (#1706). So the billed figure the monitor can see on claude is essentially cache_creation
        // alone, and "~2.6x" was one room's under-read ratio (dispatch-implement-3dc5e21a's), not a
        // per-vendor constant -- the other evidence room's ratio is 1.29x. These rooms therefore look
        // SLOW to this trigger by construction, which is precisely how #1691's premise was arrived at --
        // an agy runaway compared against claude references. spec/baton.md §3 and #1706, the issue cited
        // there, carry it; do not read 129,143 as "this lane's true 5-minute burn".
        var room = LoadFixture()[roomName];
        Assert.Equal("claude", room.Vendor);
        Assert.True(room.OffsetsAreMeasured);
        Assert.Equal("Natural", room.ExitReason);
        Assert.False(room.Cancelled);

        var result = Replay(room, ProposedRateLimit);

        Assert.False(result.Monitor.Arrested);
        Assert.Equal(-1, result.ArrestedAtSample);
        Assert.Equal(expectedPeak, result.Monitor.SnapshotPeakBilledInWindow());
        Assert.True(expectedPeak < ProposedRateLimit);
    }

    [Fact]
    public void FALSE_POSITIVE_the_proposed_limit_arrests_a_normal_agy_lane_that_ran_to_natural_completion()
    {
        // The finding that stops `billed_rate_limit` from shipping as a role default. Room 6142bd07 is
        // the runaway's OWN population -- same role, same vendor, same adapter default -- and it
        // journalled executionSucceeded with no executionFailed, and burned 1,198,800 billed -- under
        // the shipped 1,200,000 budget, though only just (0.1%), and comfortably under the shipped 610
        // tool-step cap. The 250,000-per-5-minutes limit arrests it at usage line 30 of 221: roughly 13%
        // of the way through a lane that produced its work. Arrest forecloses retry, so this is a
        // permanently killed legitimate lane, not a retried one -- and 13% is categorically different
        // from the budget's 99.9%, which is the whole point.
        var room = LoadFixture()[NormalAgyRoom];
        Assert.Equal("agy", room.Vendor);
        Assert.Equal("Natural", room.ExitReason);
        Assert.False(room.Cancelled);
        // The load-bearing one: a Natural uncancelled exit alone would NOT establish this room produced
        // anything (#1707 review found a triple-retry contract failure passing that weaker filter).
        Assert.True(room.ProducedWork, "this room must have DELIVERED for its false-arrest to be a cost.");
        Assert.True(room.TotalBilled < 1_200_000, "this room must sit UNDER the shipped token budget for the point to hold.");

        var result = Replay(room, ProposedRateLimit);

        Assert.True(result.Monitor.Arrested);
        Assert.Equal(ArrestReason.BilledRate, result.Monitor.ArrestReasonValue);
        Assert.Equal(29, result.ArrestedAtSample);
        Assert.Equal(221, room.Samples.Count);
        Assert.Equal(255_121, result.BilledAtArrest);
    }

    [Fact]
    public void CALIBRATION_no_rate_limit_separates_the_runaway_from_lanes_that_delivered()
    {
        // The separation argument, read out of the CAPTURED sweep rather than retyped from a terminal.
        // #1707 review found the first version of this test compared eight hardcoded doubles against a
        // ninth and could not fail on anything -- prose in C#. It now reads the `separation` block the
        // fixture generator writes, so a regeneration against a changed corpus moves the assertion.
        // spec/baton.md §3 has the full case; the quantities involve NO reconstruction (each room's
        // measured billed total over its measured execution span), which is why the finding rests here
        // and not on the windowed peaks above.
        var separation = LoadSeparation();

        Assert.Equal(RunawayRoom, separation.ReferenceRoom);
        Assert.NotEmpty(separation.FasterAndDelivered);

        foreach (var (room, rate) in separation.FasterAndDelivered)
        {
            Assert.True(rate > separation.ReferenceTokensPerMinute,
                $"{room} at {rate} tokens/min is not faster than the reference's {separation.ReferenceTokensPerMinute} — the fixture's separation block is inconsistent; regenerate it.");
        }

        // The heart of it: the closest room that DELIVERED is within 10% of the runaway's rate, so there
        // is not even a marginal gap to put a threshold in. If a regeneration ever pushes this above
        // 1.10, a rate default may have become defensible and spec/baton.md §3's ruling is due a
        // re-read -- which is exactly the drift this assertion exists to surface.
        var closest = separation.FasterAndDelivered.Min(r => r.TokensPerMinute);
        Assert.True(closest / separation.ReferenceTokensPerMinute < 1.10,
            $"the closest room that delivered is {closest / separation.ReferenceTokensPerMinute:0.00}x the reference — the populations no longer interleave, so re-run tools/room-rate-sweep/sweep.py and revisit spec/baton.md §3.");

        // "Delivered" is the discriminating half and the one #1707 review caught being fudged: a
        // `Natural` uncancelled exit only means the PROCESS ended cleanly. The generator's filter reads
        // executionSucceeded/executionFailed, so this count is strictly under the swept total.
        Assert.True(separation.RoomsThatDelivered < separation.RoomsSwept);
        Assert.True(separation.FasterAndDelivered.Count < separation.RoomsThatDelivered);
    }
}
